//! MAC vendor lookup: a bundled common-prefix table plus an optional online
//! fallback for prefixes that are not in the local snapshot.

use std::collections::HashMap;
use std::sync::OnceLock;
use std::time::Duration;

use serde::Deserialize;

use crate::control::ProbeHandle;
use crate::model::{MacVendorResult, MacVendorSource, ProbeEvent};

/// Public source shown next to online results.
pub const MAC_LOOKUP_SOURCE: &str = "https://maclookup.app";
/// Service terms shown next to the online lookup controls.
pub const MAC_LOOKUP_TERMS: &str = "https://maclookup.app/terms-and-conditions";
/// Base URL of the online API.
const MAC_LOOKUP_API: &str = "https://api.maclookup.app/v2/macs";

const USER_AGENT: &str = "net-tools";

/// Local OUI/MA-M/MA-S snapshot generated by `scripts/update_mac_oui.py`.
const LOCAL_TSV: &str = include_str!("mac_oui.tsv");

/// A normalized MAC address or prefix.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NormalizedMac {
    /// Uppercase hexadecimal digits without separators.
    pub hex: String,
    /// Display form with colon separators.
    pub display: String,
}

impl NormalizedMac {
    /// First six hexadecimal digits, sent to the online service.
    pub fn oui(&self) -> &str {
        &self.hex[..6]
    }
}

/// Parse a MAC address or prefix with optional separators.
///
/// At least six and at most twelve hexadecimal digits are accepted. Seven and
/// nine digits are valid MA-M and MA-S prefixes.
pub fn normalize_mac(input: &str) -> Result<NormalizedMac, String> {
    let input = input.trim();
    if input.is_empty() {
        return Err("MAC address is empty".to_string());
    }
    if !input
        .chars()
        .all(|c| c.is_ascii_hexdigit() || matches!(c, ':' | '-' | '.' | ' '))
    {
        return Err(format!("`{input}` contains invalid MAC address characters"));
    }
    let mut hex: String = input
        .chars()
        .filter(|c| c.is_ascii_hexdigit())
        .collect::<String>()
        .to_ascii_uppercase();
    if !(6..=12).contains(&hex.len()) {
        return Err(format!(
            "`{input}` must contain between six and twelve hexadecimal digits"
        ));
    }
    let display = hex
        .as_bytes()
        .chunks(2)
        .map(|chunk| std::str::from_utf8(chunk).unwrap_or_default())
        .collect::<Vec<_>>()
        .join(":");
    // Keep the prefix usable for display; the raw hex is the lookup key.
    hex.shrink_to_fit();
    Ok(NormalizedMac { hex, display })
}

struct LocalTable {
    ma_l: HashMap<u32, String>,
    ma_m: HashMap<u32, String>,
    ma_s: HashMap<u64, String>,
}

static LOCAL_TABLE: OnceLock<LocalTable> = OnceLock::new();

fn local_table() -> &'static LocalTable {
    LOCAL_TABLE.get_or_init(|| {
        let mut table = LocalTable {
            ma_l: HashMap::new(),
            ma_m: HashMap::new(),
            ma_s: HashMap::new(),
        };
        for line in LOCAL_TSV.lines() {
            let line = line.trim_end_matches('\r');
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            if line.starts_with("prefix\t") {
                continue;
            }
            let Some((prefix, vendor)) = line.split_once('\t') else {
                continue;
            };
            let prefix = prefix.trim().to_ascii_uppercase();
            let vendor = vendor.trim();
            match prefix.len() {
                6 => {
                    if let Ok(value) = u32::from_str_radix(&prefix, 16) {
                        table.ma_l.insert(value, vendor.to_string());
                    }
                }
                7 => {
                    if let Ok(value) = u32::from_str_radix(&prefix, 16) {
                        table.ma_m.insert(value, vendor.to_string());
                    }
                }
                9 => {
                    if let Ok(value) = u64::from_str_radix(&prefix, 16) {
                        table.ma_s.insert(value, vendor.to_string());
                    }
                }
                _ => {}
            }
        }
        table
    })
}

/// Look up a MAC or prefix in the bundled table.
pub fn lookup_local(input: &str) -> Result<Option<MacVendorResult>, String> {
    let mac = normalize_mac(input)?;
    Ok(lookup_normalized_local(&mac))
}

fn lookup_normalized_local(mac: &NormalizedMac) -> Option<MacVendorResult> {
    let table = local_table();
    let hex = &mac.hex;
    let mut found: Option<(String, &'static str, String)> = None;

    if hex.len() >= 9 {
        if let Ok(value) = u64::from_str_radix(&hex[..9], 16) {
            if let Some(vendor) = table.ma_s.get(&value) {
                found = Some((hex[..9].to_string(), "MA-S", vendor.clone()));
            }
        }
    }
    if found.is_none() && hex.len() >= 7 {
        if let Ok(value) = u32::from_str_radix(&hex[..7], 16) {
            if let Some(vendor) = table.ma_m.get(&value) {
                found = Some((hex[..7].to_string(), "MA-M", vendor.clone()));
            }
        }
    }
    if found.is_none() && hex.len() >= 6 {
        if let Ok(value) = u32::from_str_radix(&hex[..6], 16) {
            if let Some(vendor) = table.ma_l.get(&value) {
                found = Some((hex[..6].to_string(), "MA-L", vendor.clone()));
            }
        }
    }

    found.map(|(prefix, block_type, vendor)| MacVendorResult {
        mac: mac.display.clone(),
        prefix,
        vendor,
        address: None,
        country: None,
        block_type: Some(block_type.to_string()),
        updated: None,
        source: MacVendorSource::Local,
    })
}

/// Response shape of the online API. Only the fields used by the UI are
/// deserialized.
#[derive(Debug, Deserialize)]
struct OnlineResponse {
    #[serde(default)]
    success: bool,
    #[serde(default)]
    found: bool,
    #[serde(default, rename = "macPrefix")]
    mac_prefix: String,
    #[serde(default)]
    company: String,
    #[serde(default)]
    address: Option<String>,
    #[serde(default)]
    country: Option<String>,
    #[serde(default, rename = "blockType")]
    block_type: Option<String>,
    #[serde(default)]
    updated: Option<String>,
}

/// Query the online service for an OUI prefix.
///
/// Only the first six hexadecimal digits are sent. A `404` and a valid response
/// with `found = false` both mean "no vendor", which is not an error.
pub async fn query_online(oui: &str, timeout_ms: u64) -> Result<Option<MacVendorResult>, String> {
    let oui = oui.trim().to_ascii_uppercase();
    if oui.len() != 6 || !oui.chars().all(|c| c.is_ascii_hexdigit()) {
        return Err("online lookup requires a six-digit OUI prefix".to_string());
    }
    let client = reqwest::Client::builder()
        .timeout(Duration::from_millis(timeout_ms.clamp(1_000, 60_000)))
        .user_agent(format!("{USER_AGENT}/{}", env!("CARGO_PKG_VERSION")))
        .build()
        .map_err(|error| format!("failed to build HTTP client: {error}"))?;
    let response = client
        .get(format!("{MAC_LOOKUP_API}/{oui}"))
        .send()
        .await
        .map_err(|error| format!("online MAC lookup failed: {error}"))?;

    let status = response.status();
    if status == reqwest::StatusCode::NOT_FOUND {
        return Ok(None);
    }
    if status == reqwest::StatusCode::TOO_MANY_REQUESTS {
        let retry = response
            .headers()
            .get(reqwest::header::RETRY_AFTER)
            .and_then(|value| value.to_str().ok())
            .map(|value| format!(" retry after {value}s"))
            .unwrap_or_default();
        return Err(format!(
            "online MAC lookup is rate limited;{retry} try again later"
        ));
    }
    if !status.is_success() {
        return Err(format!("online MAC lookup returned HTTP {status}"));
    }

    let body_text = response
        .text()
        .await
        .map_err(|error| format!("failed to read online MAC lookup response: {error}"))?;
    let body: OnlineResponse = serde_json::from_str(&body_text)
        .map_err(|error| format!("failed to parse online MAC lookup response: {error}"))?;
    if !body.success || !body.found {
        return Ok(None);
    }
    let vendor = body.company.trim();
    if vendor.is_empty() {
        return Ok(None);
    }
    Ok(Some(MacVendorResult {
        mac: format_prefix_display(&oui),
        prefix: if body.mac_prefix.trim().is_empty() {
            oui
        } else {
            body.mac_prefix.trim().to_ascii_uppercase()
        },
        vendor: vendor.to_string(),
        address: body.address.filter(|value| !value.trim().is_empty()),
        country: body.country.filter(|value| !value.trim().is_empty()),
        block_type: body.block_type.filter(|value| !value.trim().is_empty()),
        updated: body.updated.filter(|value| !value.trim().is_empty()),
        source: MacVendorSource::Online,
    }))
}

fn format_prefix_display(hex: &str) -> String {
    hex.as_bytes()
        .chunks(2)
        .map(|chunk| std::str::from_utf8(chunk).unwrap_or_default())
        .collect::<Vec<_>>()
        .join(":")
}

/// Online lookup task started by the UI after a local miss.
pub async fn run_online_lookup(handle: &ProbeHandle<ProbeEvent>, input: &str, timeout_ms: u64) {
    let mac = match normalize_mac(input) {
        Ok(mac) => mac,
        Err(message) => {
            handle.send(ProbeEvent::Error {
                message,
                hint: None,
            });
            handle.send(ProbeEvent::Finished);
            return;
        }
    };
    match query_online(mac.oui(), timeout_ms).await {
        Ok(Some(result)) => handle.send(ProbeEvent::MacVendor(result)),
        Ok(None) => handle.send(ProbeEvent::Info(format!(
            "no vendor found for OUI {}",
            mac.oui()
        ))),
        Err(message) => handle.send(ProbeEvent::Error {
            message,
            hint: Some(format!("service: {MAC_LOOKUP_SOURCE}")),
        }),
    }
    handle.send(ProbeEvent::Finished);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn common_formats_are_normalized() {
        let mac = normalize_mac("aa-bb-cc-dd-ee-ff").unwrap();
        assert_eq!(mac.hex, "AABBCCDDEEFF");
        assert_eq!(mac.display, "AA:BB:CC:DD:EE:FF");
        assert_eq!(mac.oui(), "AABBCC");

        let prefix = normalize_mac("00:00:0C").unwrap();
        assert_eq!(prefix.hex, "00000C");
        assert_eq!(prefix.display, "00:00:0C");
    }

    #[test]
    fn invalid_prefixes_are_rejected() {
        assert!(normalize_mac("").is_err());
        assert!(normalize_mac("00:00").is_err());
        assert!(normalize_mac("00:00:0C:00:00:00:00").is_err());
    }

    #[test]
    fn local_table_contains_common_vendors() {
        let result = lookup_local("00:00:0C:12:34:56").unwrap().unwrap();
        assert_eq!(result.prefix, "00000C");
        assert!(result.vendor.to_lowercase().contains("cisco"));
        assert_eq!(result.source, MacVendorSource::Local);
    }

    #[test]
    fn local_lookup_misses_unknown_prefixes() {
        // This prefix is deliberately outside the curated vendor list.
        let result = lookup_local("02:00:00:00:00:01").unwrap();
        assert!(result.is_none());
    }
}
